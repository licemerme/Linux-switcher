# Switcher Linux - user config (flat TOML).
# Managed by the tray UI; safe to edit by hand. The daemon re-reads it on the
# ipc command "config.reload".
from __future__ import annotations

import os
import tomllib

APP = "switcher_linux"


def _xdg(env, default):
    v = os.environ.get(env)
    return v if v else os.path.expanduser(default)


def _runtime_dir():
    # XDG_RUNTIME_DIR is missing under nohup / autostart / cron, which used to
    # put the socket in /tmp while the daemon kept it in /run/user/<uid>.
    # Fall back to the standard per-user runtime dir, then to /tmp.
    v = os.environ.get("XDG_RUNTIME_DIR")
    if v and os.path.isdir(v):
        return v
    fallback = "/run/user/" + str(os.getuid())
    if os.path.isdir(fallback):
        return fallback
    return "/tmp"


class Paths:
    # All paths the app touches; XDG-compliant.
    def __init__(self):
        self.config_dir = os.path.join(_xdg("XDG_CONFIG_HOME", "~/.config"), APP)
        self.data_dir = os.path.join(_xdg("XDG_DATA_HOME", "~/.local/share"), APP)
        self.runtime_dir = _runtime_dir()
        self.config = os.path.join(self.config_dir, "config.toml")
        self.learned = os.path.join(self.config_dir, "learned.json")
        self.blocked = os.path.join(self.config_dir, "blocked.json")
        self.log = os.path.join(self.data_dir, "switcher.log")
        self.socket = os.path.join(self.runtime_dir, APP + ".sock")
        # Safety net: if the current XDG_RUNTIME_DIR has no socket but the
        # per-user runtime dir does (started from a different session/env),
        # talk to the one that actually exists.
        alt = os.path.join("/run/user/" + str(os.getuid()), APP + ".sock")
        if not os.path.exists(self.socket) and os.path.exists(alt):
            self.socket = alt

    def ensure(self):
        os.makedirs(self.config_dir, exist_ok=True)
        os.makedirs(self.data_dir, exist_ok=True)


paths = Paths()

DEFAULTS = {
    "min_len": 3,
    "settle": 0.45,
    "settle_dbus": 0.06,
    "gap_bs": 0.012,
    "gap_type": 0.012,
    "debug": False,
}


def _coerce(key, value):
    # Cast a TOML value to the type of its default; ignore nonsense.
    default = DEFAULTS[key]
    if isinstance(default, bool):
        return value if isinstance(value, bool) else default
    if isinstance(default, int):
        try:
            return int(value)
        except (TypeError, ValueError):
            return default
    if isinstance(default, float):
        try:
            return float(value)
        except (TypeError, ValueError):
            return default
    return value


def load():
    # Read config.toml, filling in defaults. Never raises.
    cfg = dict(DEFAULTS)
    try:
        with open(paths.config, "rb") as f:
            raw = tomllib.load(f)
    except (FileNotFoundError, OSError, tomllib.TOMLDecodeError):
        return cfg
    for k, v in raw.items():
        if k in DEFAULTS:
            cfg[k] = _coerce(k, v)
    return cfg


def _fmt(v):
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    s = str(v)
    if chr(34) in s or chr(10) in s:
        raise ValueError("config value must not contain quotes or newlines")
    return chr(34) + s + chr(34)


def save(cfg):
    # Atomic write of the whole config (tmp + rename).
    paths.ensure()
    nl = chr(10)
    lines = ["# Switcher Linux - flat TOML. Regenerated by the tray UI.",
             "# Editing by hand is fine; the daemon re-reads on config.reload.", ""]
    for k in DEFAULTS:
        if k in cfg:
            lines.append(k + " = " + _fmt(cfg[k]))
    tmp = paths.config + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(nl.join(lines) + nl)
    os.replace(tmp, paths.config)


def ensure_files():
    # Load (or create) the config file; returns the effective config.
    paths.ensure()
    cfg = load()
    if not os.path.exists(paths.config):
        save(cfg)
    return cfg
